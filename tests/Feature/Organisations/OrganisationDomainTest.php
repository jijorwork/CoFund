<?php

use App\Domain\Organisations\Actions\CreateBranch;
use App\Domain\Organisations\Actions\CreateOrganisation;
use App\Domain\Organisations\Enums\OrganisationStatus;
use App\Domain\Organisations\Enums\OrganisationType;
use App\Domain\Organisations\Models\Branch;
use App\Domain\Organisations\Models\Organisation;
use Illuminate\Database\QueryException;
use Illuminate\Support\Str;

test('an organisation can be created through its action', function () {
    $organisation = app(CreateOrganisation::class)->handle([
        'name' => 'Adom Susu',
        'code' => 'adom',
        'organisation_type' => OrganisationType::Susu,
        'status' => OrganisationStatus::Active,
    ]);

    expect($organisation)->toBeInstanceOf(Organisation::class)
        ->and(Str::isUuid($organisation->public_id))->toBeTrue()
        ->and($organisation->code)->toBe('ADOM')
        ->and($organisation->currency_code)->toBe('GHS')
        ->and($organisation->timezone)->toBe('Africa/Accra')
        ->and($organisation->organisation_type)->toBe(OrganisationType::Susu)
        ->and($organisation->status)->toBe(OrganisationStatus::Active);
});

test('organisation codes are globally unique', function () {
    Organisation::factory()->create(['code' => 'UNIQUE']);

    expect(fn () => Organisation::factory()->create(['code' => 'UNIQUE']))
        ->toThrow(QueryException::class);
});

test('organisation public ids are generated by the model', function () {
    $organisation = Organisation::query()->create([
        'name' => 'Model Generated ID',
        'code' => 'MODEL-ID',
        'organisation_type' => OrganisationType::Other,
        'currency_code' => 'GHS',
        'timezone' => 'Africa/Accra',
    ]);

    expect(Str::isUuid($organisation->public_id))->toBeTrue();
});

test('soft deleted organisations are excluded but retained', function () {
    $organisation = Organisation::factory()->create();

    $organisation->delete();

    expect(Organisation::query()->find($organisation->id))->toBeNull()
        ->and(Organisation::withTrashed()->find($organisation->id))->not->toBeNull();
});

test('a branch can be created for an organisation through its action', function () {
    $organisation = Organisation::factory()->create();

    $branch = app(CreateBranch::class)->handle($organisation, [
        'name' => 'Accra Central',
        'code' => 'acc',
    ]);

    expect($branch)->toBeInstanceOf(Branch::class)
        ->and(Str::isUuid($branch->public_id))->toBeTrue()
        ->and($branch->code)->toBe('ACC')
        ->and($branch->organisation->is($organisation))->toBeTrue();
});

test('branch codes are unique within an organisation', function () {
    $organisation = Organisation::factory()->create();

    Branch::factory()->for($organisation)->create(['code' => 'MAIN']);

    expect(fn () => Branch::factory()->for($organisation)->create(['code' => 'MAIN']))
        ->toThrow(QueryException::class);
});

test('the same branch code may be used by different organisations', function () {
    $firstOrganisation = Organisation::factory()->create();
    $secondOrganisation = Organisation::factory()->create();

    $firstBranch = Branch::factory()->for($firstOrganisation)->create(['code' => 'MAIN']);
    $secondBranch = Branch::factory()->for($secondOrganisation)->create(['code' => 'MAIN']);

    expect($firstBranch->code)->toBe($secondBranch->code)
        ->and($firstBranch->organisation_id)->not->toBe($secondBranch->organisation_id);
});
