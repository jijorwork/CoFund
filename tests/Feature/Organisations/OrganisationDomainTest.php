test('organisation profile updates require organisation-wide context and explicit permission', function () {
    $this->seed(SystemAuthorizationSeeder::class);
    $organisation = Organisation::factory()->create();
    $branch = Branch::factory()->for($organisation)->create();
    $branchActor = User::factory()->create();
    $branchAssignment = OrganisationUserRole::factory()
        ->for($branchActor)
        ->for($organisation)
        ->for($branch)
        ->state([
            'role_id' => Role::findByName(SystemRole::OrganisationAdmin->value)->getKey(),
        ])
        ->create();
    $context = app(TenantContext::class);
    $context->setOrganisation($organisation);
    $context->setBranch($branch);
    $context->setRoleAssignment($branchAssignment->load('role'));
    $attributes = [
        'name' => 'Updated Organisation',
        'code' => 'updated',
        'phone' => null,
        'email' => null,
        'address' => null,
    ];

    expect(fn () => app(UpdateOrganisationProfile::class)->handle($organisation, $attributes))
        ->toThrow(
            InvalidOrganisationAccess::class,
            'Organisation profiles can only be updated from an organisation-wide context.',
        );

    $treasurer = User::factory()->create();
    $treasurerAssignment = OrganisationUserRole::factory()
        ->for($treasurer)
        ->for($organisation)
        ->state([
            'role_id' => Role::findByName(SystemRole::Treasurer->value)->getKey(),
        ])
        ->create();
    $context->setBranch(null);
    $context->setRoleAssignment($treasurerAssignment->load('role'));

    expect(fn () => app(UpdateOrganisationProfile::class)->handle($organisation, $attributes))
        ->toThrow(PermissionDenied::class);
});

test('soft deleted organisations are excluded but retained', function () {
    $organisation = Organisation::factory()->create();

    $organisation->delete();

    expect(Organisation::query()->find($organisation->id))->toBeNull()
        ->and(Organisation::withTrashed()->find($organisation->id))->not->toBeNull();
});

