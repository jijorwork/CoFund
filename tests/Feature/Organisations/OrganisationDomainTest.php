test('an organisation can be created through its action', function () {
    $organisation = app(CreateOrganisation::class)->handle([
        'name' => 'Adom Susu',
        'code' => 'adom',
        'organisation_type' => OrganisationType::Susu,
        'status' => OrganisationStatus::Active,
    ]);

    expect($organisation)->toBeInstanceOf(Organisation::class)
        ->and(Str::isUuid($organisation->public_id))->toBeTrue()
        ->and($organisation->code)->toBe('ADOM')
        ->and($organisation->currency_code)->toBe('GHS')
        ->and($organisation->timezone)->toBe('Africa/Accra')
        ->and($organisation->organisation_type)->toBe(OrganisationType::Susu)
        ->and($organisation->status)->toBe(OrganisationStatus::Active);
});

test('organisation codes are globally unique', function () {
    Organisation::factory()->create(['code' => 'UNIQUE']);

    expect(fn () => Organisation::factory()->create(['code' => 'UNIQUE']))
