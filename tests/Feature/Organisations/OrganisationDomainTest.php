test('an organisation profile can be updated through its authorised domain action', function () {
    $this->seed(SystemAuthorizationSeeder::class);
    $actor = User::factory()->create();
    $organisation = Organisation::factory()->create([
        'organisation_type' => OrganisationType::Cooperative,
        'status' => OrganisationStatus::Active,
        'currency_code' => 'GHS',
        'timezone' => 'Africa/Accra',
    ]);
    $assignment = OrganisationUserRole::factory()
        ->for($actor)
        ->for($organisation)
        ->state([
            'role_id' => Role::findByName(SystemRole::OrganisationAdmin->value)->getKey(),
        ])
        ->create();
    $context = app(TenantContext::class);
    $context->setOrganisation($organisation);
    $context->setBranch(null);
    $context->setRoleAssignment($assignment->load('role'));

    $updated = app(UpdateOrganisationProfile::class)->handle($organisation, [
        'name' => 'Updated Cooperative',
        'code' => 'updated',
        'phone' => '+233240000000',
        'email' => 'office@example.test',
        'address' => 'Accra',
    ]);

    expect($updated->name)->toBe('Updated Cooperative')
        ->and($updated->code)->toBe('UPDATED')
        ->and($updated->phone)->toBe('+233240000000')
        ->and($updated->email)->toBe('office@example.test')
        ->and($updated->address)->toBe('Accra')
        ->and($updated->organisation_type)->toBe(OrganisationType::Cooperative)
        ->and($updated->status)->toBe(OrganisationStatus::Active)
        ->and($updated->currency_code)->toBe('GHS')
        ->and($updated->timezone)->toBe('Africa/Accra');
});

